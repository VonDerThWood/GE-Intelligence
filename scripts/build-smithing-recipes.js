/**
 * Rebuilds SMITHING_PRODUCTS in src/renderer.js from the RuneScape Wiki's
 * "Products" table on each bar's page (Ben, 2026-11-08). Anvil recipes only:
 * no smelting, Superheat or Invention. Run again after Jagex changes Smithing:
 *   node scripts/build-smithing-recipes.js
 * Output format, per bar: [outputQty, outputName, [[material, qty], ...]]
 * Upgrades (+1..+5) list the item below them as a material; the renderer
 * flattens that chain so every bar from the base item up is counted.
 */
const fs = require('fs');
const path = require('path');

const BARS = ['Bronze bar', 'Iron bar', 'Steel bar', 'Mithril bar', 'Adamant bar', 'Rune bar',
  'Orikalkum bar', 'Necronium bar', 'Bane bar', 'Elder rune bar', 'Primal bar'];
const UA = { 'User-Agent': 'GEnius smithing recipe builder (github.com/VonDerThWood/GE-Intelligence)' };
const dec = s => s.replace(/&#039;/g, "'").replace(/&amp;/g, '&').replace(/&quot;/g, '"');

async function productsFor(bar) {
  const url = `https://runescape.wiki/api.php?action=parse&page=${encodeURIComponent(bar.replace(/ /g, '_'))}&prop=text&format=json`;
  const html = (await (await fetch(url, { headers: UA })).json()).parse.text['*'];
  const from = html.search(/id="Products"/);
  const body = from >= 0 ? html.slice(from) : html;
  const starts = [...body.matchAll(/<td data-sort-value="[^"]+">([\d,]+) × <a href="[^"]*" title="([^"]+)"/g)];
  const out = [], seen = new Set();
  starts.forEach((m, i) => {
    const seg = body.slice(m.index, i + 1 < starts.length ? starts[i + 1].index : undefined);
    const facility = seg.slice(0, 5000);
    if (!/title="(Anvil|Barbarian anvil)"/.test(facility) || /title="(Superheat Item|Inventor&#039;s workbench|Inventor's workbench)"/.test(facility)) return;
    const name = dec(m[2]);
    if (seen.has(name)) return;
    seen.add(name);
    const mats = [...seg.matchAll(/white-space:pre">([\d,]+) × <\/td>[\s\S]*?title="([^"]+)"/g)].map(x => [dec(x[2]), +x[1].replace(/,/g, '')]);
    if (!mats.some(([n]) => n === bar)) return;
    out.push([+m[1].replace(/,/g, ''), name, mats]);
  });
  return out;
}

(async () => {
  const all = {};
  for (const bar of BARS) {
    all[bar] = await productsFor(bar);
    console.log(`${bar}: ${all[bar].length} products`);
    await new Promise(r => setTimeout(r, 500));
  }
  const file = path.join(__dirname, '..', 'src', 'renderer.js');
  let src = fs.readFileSync(file, 'utf8');
  const begin = '// BEGIN SMITHING_PRODUCTS (generated by scripts/build-smithing-recipes.js)';
  const end = '// END SMITHING_PRODUCTS';
  const eol = src.includes('\r\n') ? '\r\n' : '\n';
  const block = begin + eol + `const SMITHING_PRODUCTS = ${JSON.stringify(all)};` + eol + end;
  const i = src.indexOf(begin), j = src.indexOf(end);
  if (i < 0 || j < 0) throw new Error('Markers not found in renderer.js');
  src = src.slice(0, i) + block + src.slice(j + end.length);
  fs.writeFileSync(file, src);
  console.log('Updated renderer.js');
})();
