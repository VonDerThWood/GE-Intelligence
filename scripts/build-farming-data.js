/**
 * Rebuilds FARMING_DATA in src/renderer.js from the RuneScape Wiki (Ben, 2026-11-23):
 * every herb, vine herb, flower, vine flower and allotment seed, with what the wiki's own
 * Farming yield calculator uses (Bucket:Infobox_seed, Module:SkillUtils/SeedData, and the
 * patch_type each seed page passes to {{Farming yield calculator}}).
 *   node scripts/build-farming-data.js
 * Research notes: research/farming/reference.md (private repo).
 */
const fs = require('fs');
const path = require('path');

const UA = { 'User-Agent': 'GEnius farming data builder (github.com/VonDerThWood/GE-Intelligence)' };
const api = async q => (await fetch('https://runescape.wiki/api.php?format=json&' + new URLSearchParams(q), { headers: UA })).json();
const sleep = ms => new Promise(r => setTimeout(r, ms));

// Patches in scope (Ben, 2026-11-23): herbs, flowers, allotments. Trees, cacti, fruit trees
// etc. keep producing until cleared, so they're left out.
const PATCHES = {
  'Herb patch': 'herb', 'Herb patch (Wilderness)': 'herb', 'Vine herb patch': 'herb',
  'Flower Patch': 'flower', 'Flower patch (Wilderness)': 'flower', 'Vine flower patch': 'flower',
  'Allotment patch': 'allotment',
};
// Extra things a planting uses up, beyond seeds (wiki seed pages).
const EXTRA_INPUTS = { 'Starbloom flower seed': [['Battlestaff', 1]] };
// Corrections the wiki's seed data hasn't caught up with yet.
const LEVEL_FIX = { 'Snape grass seed': 34 }; // late-game rebalance, 2026-11-23 (was 80)

(async () => {
  const fields = ['page_name', 'level', 'patch', 'seed_amount', 'harvest_life', 'max_harvest_action', 'yield_per_harvest', 'protections_json', 'cycle', 'cycle_length', 'crop_json'];
  const q = `bucket('infobox_seed').select(${fields.map(f => `'${f}'`).join(',')}).limit(500).run()`;
  const rows = (await api({ action: 'bucket', query: q })).bucket;
  const lua = (await api({ action: 'parse', page: 'Module:SkillUtils/SeedData', prop: 'wikitext' })).parse.wikitext['*'];
  const lowHigh = {};
  for (const m of lua.matchAll(/\['seed'\]='([^']+)', \['low'\]=(\d+), \['high'\]=(\d+)/g)) lowHigh[m[1]] = [+m[2], +m[3]];

  const seeds = [];
  for (const r of rows) {
    const patches = [].concat(r.patch || []);
    const group = patches.map(p => PATCHES[p]).find(Boolean);
    if (!group) continue;
    let crop = null;
    try { crop = JSON.parse(r.crop_json || '[]').find(c => c.name && c.name !== 'None'); } catch {}
    if (!crop || crop.skill) continue; // "Experience" crops (sunchoke, fly trap)
    let pay = null;
    try {
      const p = JSON.parse(r.protections_json || '[]').find(x => x.type === 'payment');
      if (p) pay = [p.name, p.amount || 1];
    } catch {}
    const key = String(r.page_name).toLowerCase().replace(/ /g, '_');
    seeds.push({
      seed: r.page_name, crop: crop.name, level: LEVEL_FIX[r.page_name] || r.level || 1, group,
      wild: patches.some(p => /Wilderness/.test(p)), vine: patches.some(p => /^Vine/.test(p)),
      seeds: r.seed_amount || 1,
      lives: r.harvest_life ? +r.harvest_life : null,
      lh: lowHigh[key] || null,
      fixed: r.max_harvest_action ? (+r.max_harvest_action) * (+(r.yield_per_harvest || 1)) : null,
      pay, extra: EXTRA_INPUTS[r.page_name] || null,
      mins: r.cycle && r.cycle_length ? Math.round(r.cycle * r.cycle_length) : null,
    });
  }
  // The wiki calculator's patch_type for each seed (decides which buffs apply, e.g. farmer_flower).
  for (let i = 0; i < seeds.length; i += 40) {
    const batch = seeds.slice(i, i + 40);
    const r = await api({ action: 'query', prop: 'revisions', rvprop: 'content', rvslots: 'main', redirects: 1, titles: batch.map(s => s.seed).join('|') });
    const byTitle = {};
    for (const p of Object.values(r.query.pages)) if (p.revisions) byTitle[p.title] = p.revisions[0].slots.main['*'];
    for (const s of batch) {
      const m = (byTitle[s.seed] || '').match(/\{\{Farming yield calculator[^}]*patch_type\s*=\s*([a-z_]+)/);
      s.ptype = m ? m[1] : (s.group === 'allotment' ? 'allotment' : s.group);
    }
    await sleep(300);
  }
  seeds.sort((a, b) => a.level - b.level);
  console.log(seeds.length, 'seeds:', seeds.map(s => `${s.seed} [${s.ptype}]`).join(', '));
  const file = path.join(__dirname, '..', 'src', 'renderer.js');
  let src = fs.readFileSync(file, 'utf8');
  const begin = '// BEGIN FARMING_DATA (generated by scripts/build-farming-data.js)';
  const end = '// END FARMING_DATA';
  const eol = src.includes('\r\n') ? '\r\n' : '\n';
  const i = src.indexOf(begin), j = src.indexOf(end);
  if (i < 0 || j < 0) throw new Error('Markers not found in renderer.js');
  src = src.slice(0, i) + begin + eol + `const FARMING_DATA = ${JSON.stringify(seeds)};` + eol + end + src.slice(j + end.length);
  fs.writeFileSync(file, src);
  console.log('Updated renderer.js');
})();
